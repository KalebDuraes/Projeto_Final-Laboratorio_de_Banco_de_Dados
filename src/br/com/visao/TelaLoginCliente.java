    private void jBentrarActionPerformed(java.awt.event.ActionEvent evt) {
        String documento = jTdigite.getText().trim();
        String senha = new String(((javax.swing.JPasswordField)jTsenha).getPassword()).trim();

        if (documento.isEmpty() || documento.equals("Digite seu CPF ou CNPJ") || senha.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Preencha todos os campos!", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        ClienteLoginDAO dao = new ClienteLoginDAO();
        try {
            boolean autenticado = dao.validarLogin(documento, senha);
            if (autenticado) {
                JOptionPane.showMessageDialog(this, "Login realizado com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
                // Abrir tela principal do cliente aqui
                this.dispose();
            } else {
                JOptionPane.showMessageDialog(this, "CPF/CNPJ ou senha inválidos.", "Erro de Autenticação", JOptionPane.ERROR_MESSAGE);
            }
        } catch (SQLException ex) {
            logger.log(java.util.logging.Level.SEVERE, "Erro ao conectar com o banco", ex);
            JOptionPane.showMessageDialog(this, "Erro de conexão com o banco de dados: " + ex.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }                                       
