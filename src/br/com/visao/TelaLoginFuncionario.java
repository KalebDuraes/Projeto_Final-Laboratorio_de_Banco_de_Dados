    private void jBEntrarFuncActionPerformed(java.awt.event.ActionEvent evt) {
        String cpf = jTusuario.getText().trim();
        String senha = new String(((javax.swing.JPasswordField)jTsenha).getPassword()).trim();

        if (cpf.isEmpty() || cpf.equals("Digite seu CPF") || senha.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Preencha todos os campos!", "Aviso", JOptionPane.WARNING_MESSAGE);
            return;
        }

        FuncionarioLoginDAO dao = new FuncionarioLoginDAO();
        try {
            boolean autenticado = dao.validarLogin(cpf, senha);
            if (autenticado) {
                JOptionPane.showMessageDialog(this, "Login de funcionário realizado com sucesso!", "Sucesso", JOptionPane.INFORMATION_MESSAGE);
                // Abrir painel administrativo/gerencial aqui
                this.dispose();
            } else {
                JOptionPane.showMessageDialog(this, "CPF ou senha de funcionário inválidos.", "Erro de Autenticação", JOptionPane.ERROR_MESSAGE);
            }
        } catch (SQLException ex) {
            logger.log(java.util.logging.Level.SEVERE, "Erro ao conectar com o banco", ex);
            JOptionPane.showMessageDialog(this, "Erro de conexão com o banco de dados: " + ex.getMessage(), "Erro", JOptionPane.ERROR_MESSAGE);
        }
    }
